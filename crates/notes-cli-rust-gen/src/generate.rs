use core::error::Error;
use core::fmt::{Display, Formatter, Result as FmtResult, Write};
use notes_cli_describe::{ArgumentSpec, CliSpec, CommandSpec, Outcome, Shape, Source};

/// A spec with no Rust declaration yet.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Undeclarable {
    /// The command it is in.
    pub operation: String,
    /// Why.
    pub reason: &'static str,
}

impl Display for Undeclarable {
    fn fmt(&self, f: &mut Formatter<'_>) -> FmtResult {
        write!(f, "`{}`: {}", self.operation, self.reason)
    }
}

impl Error for Undeclarable {}

/// The name of the extension `generate` declares for `spec`: `NotesCliExt` for `notes`.
fn ext_name(spec: &CliSpec) -> String {
    format!("{}CliExt", pascal(&spec.name.replace('-', "_")))
}

/// Generates the declaration of `spec`: `<Name>CliExt` with the method `<name>_cli::<Machine>`,
/// which applies each operation as `Machine::<operation>`.
///
/// # Errors
///
/// Answers with the first command the generator cannot declare.
pub fn generate(spec: &CliSpec) -> Result<String, Undeclarable> {
    let name = spec.name.replace('-', "_");
    // Each `Machine::<operation>` names the operation's reified type, and its argument names when
    // it takes any, so the parent module defines exactly these.
    let mut reified = Vec::new();
    for command in &spec.commands {
        let operation = &command.operation;
        reified.push(format!("Op_{operation}"));
        if !command.arguments.is_empty() {
            reified.push(format!("ArgNames_{operation}"));
        }
    }
    let mut out = format!(
        "// Generated by `notes-cli-rust-gen` from the `{program}` spec; change the spec, not this file.

use super::{{{reified}}};
use alux_cli::{{CliCommandsAlg, cli}};
use alux_ext::ext;

/// The `{program}` command line, generated from its spec.
#[ext(name = {ext}, defunc(via = cli))]
pub impl<This> This
where
    This: CliCommandsAlg,
{{
    /// Declares the `{program}` command line.
    #[rustfmt::skip]
    fn {name}_cli<Machine>(&self) {{
",
        program = spec.name,
        reified = reified.join(", "),
        ext = ext_name(spec),
    );
    for command in &spec.commands {
        declare(command, &mut out)?;
    }
    out.push_str("\n        self.commands()");
    // `.cmd_root(` and `.cmd("name",` are padded alike, so the operations line up.
    let heads = spec
        .commands
        .iter()
        .map(|command| match command.path.as_slice() {
            [] => ".cmd_root(".to_owned(),
            [name] => format!(".cmd({name:?},"),
            _ => unreachable!("declare rejects deeper paths"),
        })
        .collect::<Vec<_>>();
    let width = heads.iter().map(String::len).max().unwrap_or(0);
    for (head, command) in heads.iter().zip(&spec.commands) {
        write!(out, "\n            {head:width$} {})", command.operation).expect("writing to a String");
    }
    out.push_str("\n    }\n}\n");
    Ok(out)
}

fn declare(command: &CommandSpec, out: &mut String) -> Result<(), Undeclarable> {
    let undeclarable = |reason| Undeclarable { operation: command.operation.clone(), reason };
    if command.path.len() > 1 {
        return Err(undeclarable("nested subcommands are not generated yet"));
    }
    let rows =
        command.arguments.iter().map(|argument| row(argument).map_err(undeclarable)).collect::<Result<Vec<_>, _>>()?;

    let mode = match command.outcome {
        Outcome::Total => None,
        Outcome::Fallible(1) => Some(".fallible()".to_owned()),
        Outcome::Fallible(status) => Some(format!(".fallible_as({status})")),
        Outcome::FallibleByError => Some(".fallible_by_error()".to_owned()),
    };
    write!(out, "        let {0} = self.op(Machine::{0})", command.operation).expect("writing to a String");
    for line in aligned(&rows) {
        write!(out, "\n            {line}").expect("writing to a String");
    }
    if let Some(mode) = mode {
        write!(out, "\n            {mode}").expect("writing to a String");
    }
    out.push_str(";\n");
    Ok(())
}

/// One argument's calls, a cell each, in the order the source builder takes them.
fn row(argument: &ArgumentSpec) -> Result<Vec<String>, &'static str> {
    let doc = format!("{:?}", argument.doc);
    let mut cells = vec![format!(".arg({:?},", argument.name)];
    match &argument.source {
        Source::Positional => {
            cells.push(format!("self.positional({doc})"));
            cells.push(match argument.shape {
                Shape::One => String::new(),
                Shape::Optional => ".optional()".to_owned(),
                Shape::Many => ".many()".to_owned(),
                Shape::Switch => return Err("a positional argument cannot be a switch"),
            });
            cells.extend([String::new(), String::new()]);
        }
        Source::Named { long, short } => {
            cells.push(format!("self.named({doc})"));
            cells.push(match argument.shape {
                Shape::One => String::new(),
                Shape::Optional => ".optional()".to_owned(),
                Shape::Many => ".many()".to_owned(),
                Shape::Switch => ".switch()".to_owned(),
            });
            let default_long = Source::default_long(&argument.name);
            cells.push(if *long == default_long { String::new() } else { format!(".long({long:?})") });
            cells.push(short.map(|short| format!(".short({short:?})")).unwrap_or_default());
        }
    }
    cells.push(argument.env.as_ref().map(|env| format!(".env({env:?})")).unwrap_or_default());
    cells.push(argument.default.as_ref().map(|default| format!(".default({default:?})")).unwrap_or_default());
    cells.push(argument.delimiter.map(|delimiter| format!(".delimiter({delimiter:?})")).unwrap_or_default());
    Ok(cells)
}

/// Pads every column to its widest cell, so the arguments read as a table, and closes each row.
fn aligned(rows: &[Vec<String>]) -> Vec<String> {
    let columns = rows.first().map_or(0, Vec::len);
    let used = (0..columns).filter(|&column| rows.iter().any(|row| !row[column].is_empty())).collect::<Vec<_>>();
    let widths =
        used.iter().map(|&column| rows.iter().map(|row| row[column].len()).max().unwrap_or(0)).collect::<Vec<_>>();
    rows.iter()
        .map(|row| {
            let last = used.iter().rposition(|&column| !row[column].is_empty()).unwrap_or(0);
            let mut line = String::new();
            for (index, (&column, &width)) in used.iter().zip(&widths).enumerate().take(last + 1) {
                let cell = &row[column];
                if index == last {
                    write!(line, "{cell})").expect("writing to a String");
                } else {
                    write!(line, "{cell:width$} ").expect("writing to a String");
                }
            }
            line
        })
        .collect()
}

fn pascal(snake: &str) -> String {
    snake
        .split('_')
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map(|first| first.to_uppercase().chain(chars).collect::<String>()).unwrap_or_default()
        })
        .collect()
}
